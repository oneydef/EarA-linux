def t(key: str, **kwargs) -> str:
    table = STRINGS.get(LANG, STRINGS["en"])
    text = table.get(key) or STRINGS["en"].get(key, key)
    return text.format(**kwargs) if kwargs else text


def _read_config() -> dict:
    try:
        data = json.loads(_CONFIG.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def _write_config(data: dict) -> None:
    _CONFIG.parent.mkdir(parents=True, exist_ok=True)
    _CONFIG.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def power_off_on_exit() -> bool:
    return bool(_read_config().get("power_off_on_exit", False))


def set_power_off_on_exit(enabled: bool) -> None:
    data = _read_config()
    data["power_off_on_exit"] = bool(enabled)
    _write_config(data)


def load_lang() -> str:
    global LANG
    lang = str(_read_config().get("lang", "en"))
    LANG = lang if lang in SUPPORTED else "en"
    return LANG


def set_lang(lang: str) -> None:
    global LANG
    LANG = lang if lang in SUPPORTED else "en"
    data = _read_config()
    data["lang"] = LANG
    _write_config(data)
